/**
 * Generic SQLite -> PostgreSQL schema converter: introspects any SQLite database (sqlite_schema + pragmas, plus the stored DDL
 * for what pragmas do not expose: CHECK, generated columns, partial/expression indexes, triggers, views) and emits PostgreSQL DDL.
 */
import type { DatabaseSync } from 'node:sqlite';
import { type ParsedTable, type Token, isOp, isWord, matchParen, parseCreateIndex, parseCreateTable, parseCreateTrigger, parseCreateView, referencedRelations, tokenize } from './sql.js';
import { type HelperName, type PgType, type TranslateContext, helperDefinitions, mapDeclaredType, quoteIdent, quoteLiteral, translateCondition, translateExpression } from './translate.js';
import { convertTrigger, pgName } from './triggers.js';

export const DEFAULT_PG_SCHEMA = 'alpha';
export const SCHEMA_NAME_PATTERN = /^[a-z_][a-z0-9_]{0,62}$/;

export interface ConvertOptions {
  /** Target PostgreSQL schema (default `alpha`). */
  schema?: string;
  /** Export the implicit rowid of rowid tables without INTEGER PRIMARY KEY as an identity column (default true). */
  rowid?: boolean;
}

export interface ColumnPlan {
  name: string;
  declaredType: string;
  pgType: PgType;
  notNull: boolean;
  /** 1-based position in the primary key, 0 when not part of it. */
  primaryKeyPosition: number;
  identity: boolean;
  /** Computed by PostgreSQL (GENERATED ALWAYS ... STORED): not copied, still verified. */
  generated: boolean;
  /** Column materialising SQLite's implicit rowid. */
  rowid: boolean;
  /** SQLite expression used to read the column. */
  source: string;
  defaultSql?: string;
  generatedSql?: string;
}

export interface CheckPlan {
  name: string;
  sql: string;
  original: string;
}

export interface TablePlan {
  name: string;
  columns: ColumnPlan[];
  primaryKey: string[];
  /** Columns with GENERATED BY DEFAULT AS IDENTITY (rowid alias or materialised rowid). */
  identityColumns: string[];
  autoincrement: boolean;
  withoutRowid: boolean;
  /** Deterministic order used by the verification checksum. */
  orderBy: string[];
  constraints: string[];
  checks: CheckPlan[];
  uniques: string[][];
  dependsOn: string[];
}

export interface IndexPlan {
  name: string;
  table: string;
  unique: boolean;
  partial: boolean;
  sql: string;
}

export interface ForeignKeyPlan {
  name: string;
  table: string;
  columns: string[];
  refTable: string;
  refColumns: string[];
  onUpdate: string;
  onDelete: string;
  initiallyDeferred: boolean;
}

export interface TriggerPlan {
  name: string;
  table: string;
  pattern: 'guard' | 'touch' | 'generic';
  functionName: string;
  functionSql: string;
  /** PostgreSQL trigger names created (a DELETE guard also blocks TRUNCATE). */
  triggerNames: string[];
  sql: string[];
}

export interface ViewPlan {
  name: string;
  sql: string;
  dependsOn: string[];
}

export interface UnsupportedObject {
  kind: 'table' | 'column' | 'check' | 'default' | 'index' | 'foreign_key' | 'trigger' | 'view';
  name: string;
  reason: string;
  sql?: string;
}

export interface ConversionResult {
  schema: string;
  sqliteVersion: string;
  helpers: { name: HelperName; sql: string }[];
  tables: TablePlan[];
  indexes: IndexPlan[];
  foreignKeys: ForeignKeyPlan[];
  triggers: TriggerPlan[];
  views: ViewPlan[];
  warnings: string[];
  unsupported: UnsupportedObject[];
  ddl: string;
}

interface SchemaObject { type: string; name: string; tableName: string; sql: string }
interface XInfoRow { cid: number; name: string; type: string; notnull: number; dflt_value: string | null; pk: number; hidden: number }
interface IndexListRow { seq: number; name: string; unique: number; origin: string; partial: number }
interface IndexXInfoRow { seqno: number; cid: number; name: string | null; desc: number; coll: string; key: number }
interface ForeignKeyRow { id: number; seq: number; table: string; from: string; to: string | null; on_update: string; on_delete: string; match: string }

const ROWID_NAMES = ['rowid', '_rowid_', 'oid'];
const NUMERIC_TYPES = new Set<PgType>(['bigint', 'double precision', 'numeric']);

export function assertSchemaName(schema: string): void {
  if (!SCHEMA_NAME_PATTERN.test(schema) || /^pg_/.test(schema) || schema === 'information_schema' || schema === 'public') {
    throw new Error(`Nom de schéma PostgreSQL invalide « ${schema} » (attendu : [a-z_][a-z0-9_]*, ni public, ni pg_*, ni information_schema).`);
  }
}

function tooLong(name: string): boolean {
  return Buffer.byteLength(name) > 63;
}

function sameColumns(a: string[], b: string[]): boolean {
  return a.length === b.length && a.every((column, index) => column.toLowerCase() === b[index].toLowerCase());
}

function sameColumnSet(a: string[], b: string[]): boolean {
  const lower = new Set(a.map((column) => column.toLowerCase()));
  return a.length === b.length && b.every((column) => lower.has(column.toLowerCase()));
}

/** Dependency-first ordering (cycles are broken in declaration order). */
function topologicalOrder<T extends { name: string; dependsOn: string[] }>(items: T[]): T[] {
  const byName = new Map(items.map((item) => [item.name.toLowerCase(), item]));
  const state = new Map<string, 'visiting' | 'done'>();
  const ordered: T[] = [];
  const visit = (item: T) => {
    const key = item.name.toLowerCase();
    if (state.get(key)) return;
    state.set(key, 'visiting');
    for (const dependency of item.dependsOn) {
      const target = byName.get(dependency.toLowerCase());
      if (target && target !== item) visit(target);
    }
    state.set(key, 'done');
    ordered.push(item);
  };
  items.forEach(visit);
  return ordered;
}

function stripParens(tokens: Token[]): Token[] {
  let current = tokens;
  while (current.length > 2 && isOp(current[0], '(') && matchParen(current, 0) === current.length - 1) current = current.slice(1, -1);
  return current;
}

export function convertSqliteSchema(db: DatabaseSync, options: ConvertOptions = {}): ConversionResult {
  const schema = options.schema ?? DEFAULT_PG_SCHEMA;
  assertSchemaName(schema);
  const preserveRowid = options.rowid ?? true;
  const s = quoteIdent(schema);
  const warnings: string[] = [];
  const unsupported: UnsupportedObject[] = [];
  const helpers = new Set<HelperName>();
  const relationNames = new Set<string>();
  const functionNames = new Set<string>(['sqlite_json_valid', 'sqlite_json_type', 'sqlite_json_array_length', 'sqlite_randomblob', 'sqlite_raise']);
  const warn = (subject: string, message: string) => {
    const line = `${subject} : ${message}`;
    if (!warnings.includes(line)) warnings.push(line);
  };
  const reject = (item: UnsupportedObject) => {
    unsupported.push(item);
    warn(`${item.kind} ${item.name}`, `non converti — ${item.reason}`);
  };

  const sqliteVersion = (db.prepare('SELECT sqlite_version() AS version').get() as { version: string }).version;
  const objects = db.prepare("SELECT type, name, tbl_name AS tableName, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite\\_%' ESCAPE '\\' ORDER BY rowid").all() as unknown as SchemaObject[];
  const tableKinds = new Map((db.prepare("SELECT name, type FROM pragma_table_list WHERE schema = 'main'").all() as { name: string; type: string }[]).map((row) => [row.name, row.type]));
  const sequences = new Map<string, number>();
  if (objects.some((item) => item.type === 'table') && db.prepare("SELECT 1 FROM sqlite_master WHERE name = 'sqlite_sequence'").get()) {
    for (const row of db.prepare('SELECT name, seq FROM sqlite_sequence').all() as { name: string; seq: number }[]) sequences.set(row.name, Number(row.seq));
  }

  // ---- Tables -------------------------------------------------------------------------------------------------------
  const parsedTables = new Map<string, ParsedTable>();
  const tables: TablePlan[] = [];
  for (const object of objects.filter((item) => item.type === 'table')) {
    const kind = tableKinds.get(object.name) ?? 'table';
    if (kind === 'shadow') continue;
    if (kind === 'virtual' || /^\s*CREATE\s+VIRTUAL/i.test(object.sql)) {
      reject({ kind: 'table', name: object.name, reason: 'table virtuelle (FTS, R-Tree…) : à remplacer par un équivalent PostgreSQL (tsvector, extension)', sql: object.sql });
      continue;
    }
    if (tooLong(object.name)) {
      reject({ kind: 'table', name: object.name, reason: 'nom de plus de 63 octets (tronqué par PostgreSQL)', sql: object.sql });
      continue;
    }
    let parsed: ParsedTable;
    try {
      parsed = parseCreateTable(object.sql);
    } catch (error) {
      reject({ kind: 'table', name: object.name, reason: `DDL illisible (${(error as Error).message})`, sql: object.sql });
      continue;
    }
    parsedTables.set(object.name.toLowerCase(), parsed);
    const xinfo = db.prepare('SELECT cid, name, type, "notnull" AS "notnull", dflt_value, pk, hidden FROM pragma_table_xinfo(?)').all(object.name) as unknown as XInfoRow[];
    const visible = xinfo.filter((row) => row.hidden !== 1);
    const long = visible.find((row) => tooLong(row.name));
    if (long) {
      reject({ kind: 'table', name: object.name, reason: `colonne « ${long.name} » de plus de 63 octets`, sql: object.sql });
      continue;
    }
    const pkRows = visible.filter((row) => row.pk > 0).sort((a, b) => a.pk - b.pk);
    const rowidAlias = !parsed.withoutRowid && pkRows.length === 1 && pkRows[0].type.toUpperCase() === 'INTEGER' ? pkRows[0].name : undefined;
    const parsedColumns = new Map(parsed.columns.map((column) => [column.name.toLowerCase(), column]));
    const subject = `table ${object.name}`;
    const columns: ColumnPlan[] = visible.map((row) => {
      const mapped = mapDeclaredType(row.type);
      if (mapped.warning && !(row.hidden === 2 || row.hidden === 3)) warn(`${subject}.${row.name}`, mapped.warning);
      const parsedColumn = parsedColumns.get(row.name.toLowerCase());
      if (parsedColumn?.collate && parsedColumn.collate !== 'BINARY') {
        warn(`${subject}.${row.name}`, `COLLATE ${parsedColumn.collate} remplacé par COLLATE "C" (comparaisons sensibles à la casse/espaces)`);
      }
      return {
        name: row.name,
        declaredType: row.type,
        pgType: mapped.type,
        notNull: row.notnull === 1 || row.pk > 0 && parsed.withoutRowid,
        primaryKeyPosition: row.pk,
        identity: row.name === rowidAlias,
        generated: false,
        rowid: false,
        source: quoteIdent(row.name),
        defaultSql: undefined as string | undefined,
        generatedSql: undefined as string | undefined,
      };
    });
    const columnMap = new Map(columns.map((column) => [column.name.toLowerCase(), column.name]));
    const columnTypes = new Map(columns.map((column) => [column.name.toLowerCase(), column.pgType]));
    const context = (mode: TranslateContext['mode']): TranslateContext => ({ schema, mode, columns: columnMap, columnTypes, tables: new Map(), helpers: new Set(), problems: [] });
    const absorb = (ctx: TranslateContext) => ctx.helpers.forEach((helper) => helpers.add(helper));

    // Defaults and generated columns.
    for (const column of columns) {
      const row = visible.find((item) => item.name === column.name)!;
      const parsedColumn = parsedColumns.get(column.name.toLowerCase());
      if (row.hidden === 2 || row.hidden === 3) {
        const ctx = context('generated');
        const expression = parsedColumn?.generated;
        const referencesGenerated = expression?.tokens.some((token) => (token.kind === 'word' || token.kind === 'quoted')
          && visible.some((other) => other !== row && (other.hidden === 2 || other.hidden === 3) && other.name.toLowerCase() === token.value.toLowerCase()));
        const sql = expression ? translateExpression(expression.tokens, ctx) : undefined;
        const errors = ctx.problems.filter((item) => item.level === 'error').map((item) => item.message);
        if (!expression) errors.push('expression introuvable dans le DDL');
        if (referencesGenerated) errors.push('référence une autre colonne calculée (interdit par PostgreSQL)');
        if (!row.type.trim()) column.pgType = 'text';
        if (errors.length) {
          reject({ kind: 'column', name: `${object.name}.${column.name}`, reason: `colonne calculée exportée comme colonne ordinaire (valeurs copiées) : ${errors.join(' ; ')}`, sql: expression?.text });
        } else {
          column.generated = true;
          column.generatedSql = sql;
          absorb(ctx);
          ctx.problems.forEach((item) => warn(`${subject}.${column.name}`, item.message));
          if (!expression!.stored) warn(`${subject}.${column.name}`, 'colonne calculée VIRTUAL exportée en STORED');
        }
        continue;
      }
      if (row.dflt_value === null || column.identity) continue;
      const tokens = stripParens(tokenize(row.dflt_value));
      if (tokens.length === 1 && isWord(tokens[0], 'NULL')) continue;
      const literal = tokens.length === 1 ? tokens[0] : tokens.length === 2 && isOp(tokens[0], '-', '+') && tokens[1].kind === 'number' ? tokens[1] : undefined;
      if (literal?.kind === 'number' && column.pgType === 'text') {
        column.defaultSql = quoteLiteral(tokens.map((token) => token.value).join(''));
        continue;
      }
      if (literal?.kind === 'string' && NUMERIC_TYPES.has(column.pgType) && !/^\s*[-+]?(\d+(\.\d*)?|\.\d+)([eE][-+]?\d+)?\s*$/.test(literal.value)) {
        reject({ kind: 'default', name: `${object.name}.${column.name}`, reason: 'texte par défaut dans une colonne numérique', sql: row.dflt_value });
        continue;
      }
      const ctx = context('default');
      const sql = translateExpression(tokens, ctx);
      const errors = ctx.problems.filter((item) => item.level === 'error');
      if (errors.length) {
        reject({ kind: 'default', name: `${object.name}.${column.name}`, reason: errors.map((item) => item.message).join(' ; '), sql: row.dflt_value });
        continue;
      }
      absorb(ctx);
      ctx.problems.forEach((item) => warn(`${subject}.${column.name} DEFAULT`, item.message));
      column.defaultSql = sql;
    }

    let rowidColumn: string | undefined;
    if (preserveRowid && !parsed.withoutRowid && !rowidAlias) {
      rowidColumn = ROWID_NAMES.find((name) => !columnMap.has(name));
      if (rowidColumn) {
        columns.push({ name: rowidColumn, declaredType: 'ROWID', pgType: 'bigint', notNull: true, primaryKeyPosition: 0, identity: true, generated: false, rowid: true, source: rowidColumn });
      } else warn(subject, 'rowid implicite non exporté (colonnes rowid, _rowid_ et oid déjà utilisées)');
    }

    const primaryKey = pkRows.map((row) => row.name);
    const constraints: string[] = [];
    if (primaryKey.length) constraints.push(`CONSTRAINT ${quoteIdent(pgName(`${object.name}_pkey`, relationNames))} PRIMARY KEY (${primaryKey.map(quoteIdent).join(', ')})`);
    if (rowidColumn) constraints.push(`CONSTRAINT ${quoteIdent(pgName(`${object.name}_${rowidColumn}_key`, relationNames))} UNIQUE (${quoteIdent(rowidColumn)})`);
    const uniques: string[][] = [];
    for (const index of db.prepare('SELECT seq, name, "unique" AS "unique", origin, partial FROM pragma_index_list(?) ORDER BY seq DESC').all(object.name) as unknown as IndexListRow[]) {
      if (index.origin !== 'u') continue;
      const keyColumns = (db.prepare('SELECT seqno, cid, name, "desc" AS "desc", coll, "key" AS "key" FROM pragma_index_xinfo(?) WHERE "key" = 1 ORDER BY seqno').all(index.name) as unknown as IndexXInfoRow[])
        .map((row) => row.name!);
      if (uniques.some((existing) => sameColumns(existing, keyColumns))) continue;
      uniques.push(keyColumns);
      constraints.push(`CONSTRAINT ${quoteIdent(pgName(`${object.name}_${keyColumns.join('_')}_key`, relationNames))} UNIQUE (${keyColumns.map(quoteIdent).join(', ')})`);
    }
    if (parsed.conflictClauses.length) warn(subject, `clauses ${parsed.conflictClauses.join(', ')} ignorées (PostgreSQL : ON CONFLICT au niveau des requêtes)`);
    if (parsed.strict) warn(subject, 'table STRICT : typage strict conservé par les types PostgreSQL');

    const checks: CheckPlan[] = [];
    const checkNames = new Set<string>();
    parsed.checks.forEach((check) => {
      const ctx = context('check');
      const sql = translateCondition(check.tokens, ctx);
      const errors = ctx.problems.filter((item) => item.level === 'error');
      const name = pgName(check.name ?? (check.column ? `${object.name}_${check.column}_check` : `${object.name}_check`), checkNames);
      if (errors.length) {
        reject({ kind: 'check', name: `${object.name}.${name}`, reason: errors.map((item) => item.message).join(' ; '), sql: `CHECK (${check.text})` });
        return;
      }
      absorb(ctx);
      ctx.problems.forEach((item) => warn(`${subject} CHECK (${check.text})`, item.message));
      checks.push({ name, sql, original: check.text });
    });

    const orderBy = primaryKey.length ? primaryKey : rowidColumn ? [rowidColumn] : rowidAlias ? [rowidAlias] : columns.map((column) => column.name);
    tables.push({
      name: object.name,
      columns,
      primaryKey,
      identityColumns: columns.filter((column) => column.identity).map((column) => column.name),
      autoincrement: parsed.columns.some((column) => column.autoincrement) || sequences.has(object.name),
      withoutRowid: parsed.withoutRowid,
      orderBy,
      constraints,
      checks,
      uniques,
      dependsOn: [],
    });
    relationNames.add(object.name.toLowerCase());
  }
  const tableByName = new Map(tables.map((table) => [table.name.toLowerCase(), table]));

  // ---- Foreign keys -------------------------------------------------------------------------------------------------
  const foreignKeys: ForeignKeyPlan[] = [];
  const constraintNames = new Map<string, Set<string>>();
  for (const table of tables) {
    const rows = db.prepare('SELECT id, seq, "table" AS "table", "from" AS "from", "to" AS "to", on_update, on_delete, match FROM pragma_foreign_key_list(?) ORDER BY id, seq').all(table.name) as unknown as ForeignKeyRow[];
    const groups = new Map<number, ForeignKeyRow[]>();
    rows.forEach((row) => groups.set(row.id, [...(groups.get(row.id) ?? []), row]));
    const parsed = parsedTables.get(table.name.toLowerCase())!;
    for (const group of [...groups.values()].reverse()) {
      const columns = group.map((row) => table.columns.find((column) => column.name.toLowerCase() === row.from.toLowerCase())?.name ?? row.from);
      const parent = tableByName.get(group[0].table.toLowerCase());
      const label = `${table.name}(${columns.join(', ')}) → ${group[0].table}`;
      if (!parent) {
        reject({ kind: 'foreign_key', name: label, reason: 'table parente absente' });
        continue;
      }
      const refColumns = group.every((row) => row.to !== null)
        ? group.map((row) => parent.columns.find((column) => column.name.toLowerCase() === row.to!.toLowerCase())?.name ?? row.to!)
        : parent.primaryKey;
      if (refColumns.length !== columns.length) {
        reject({ kind: 'foreign_key', name: label, reason: 'la table parente n’a pas de clé primaire correspondante' });
        continue;
      }
      if (!sameColumnSet(parent.primaryKey, refColumns) && !parent.uniques.some((unique) => sameColumnSet(unique, refColumns))
        && !findUniqueIndex(db, parent.name, refColumns)) {
        reject({ kind: 'foreign_key', name: label, reason: 'colonnes parentes sans contrainte d’unicité (« foreign key mismatch » dans SQLite)' });
        continue;
      }
      const mismatch = columns.findIndex((column, index) => {
        const child = table.columns.find((item) => item.name === column)?.pgType;
        const target = parent.columns.find((item) => item.name === refColumns[index])?.pgType;
        return !child || !target || (child !== target && !(NUMERIC_TYPES.has(child) && NUMERIC_TYPES.has(target)));
      });
      if (mismatch !== -1) {
        reject({ kind: 'foreign_key', name: label, reason: `types incompatibles pour ${columns[mismatch]} → ${refColumns[mismatch]}` });
        continue;
      }
      const reference = parsed.references.find((item) => sameColumns(item.columns, columns) && item.table.toLowerCase() === parent.name.toLowerCase());
      const names = constraintNames.get(table.name) ?? new Set<string>();
      constraintNames.set(table.name, names);
      foreignKeys.push({
        name: pgName(`${table.name}_${columns.join('_')}_fkey`, names),
        table: table.name,
        columns,
        refTable: parent.name,
        refColumns,
        onUpdate: group[0].on_update.toUpperCase(),
        onDelete: group[0].on_delete.toUpperCase(),
        initiallyDeferred: reference?.initiallyDeferred ?? false,
      });
      if (group[0].match && group[0].match.toUpperCase() !== 'NONE') warn(`table ${table.name}`, `MATCH ${group[0].match} ignoré (SQLite applique MATCH SIMPLE)`);
      if (parent !== table) table.dependsOn.push(parent.name);
    }
  }

  // ---- Indexes ------------------------------------------------------------------------------------------------------
  const indexes: IndexPlan[] = [];
  for (const object of objects.filter((item) => item.type === 'index')) {
    const table = tableByName.get(object.tableName.toLowerCase());
    if (!table) {
      reject({ kind: 'index', name: object.name, reason: `table ${object.tableName} non exportée`, sql: object.sql });
      continue;
    }
    try {
      const parsed = parseCreateIndex(object.sql);
      const columnMap = new Map(table.columns.map((column) => [column.name.toLowerCase(), column.name]));
      const ctx: TranslateContext = { schema, mode: 'index', columns: columnMap, columnTypes: new Map(table.columns.map((column) => [column.name.toLowerCase(), column.pgType])), tables: new Map(), helpers: new Set(), problems: [] };
      const parts = parsed.columns.map((column) => {
        const simple = column.tokens.length === 1 && (column.tokens[0].kind === 'word' || column.tokens[0].kind === 'quoted') ? columnMap.get(column.tokens[0].value.toLowerCase()) : undefined;
        let sql = simple ? quoteIdent(simple) : `(${translateExpression(column.tokens, ctx)})`;
        if (column.collate === 'NOCASE') {
          sql = `(lower(${simple ? sql : sql.slice(1, -1)}))`;
          warn(`index ${object.name}`, `${column.text} COLLATE NOCASE indexé sous la forme lower(...) (insensibilité à la casse ASCII conservée pour l’unicité)`);
        } else if (column.collate && column.collate !== 'BINARY') {
          warn(`index ${object.name}`, `COLLATE ${column.collate} ignoré`);
        }
        return `${sql}${column.descending ? ' DESC' : ''}`;
      });
      const where = parsed.where ? translateCondition(parsed.where, ctx) : undefined;
      const errors = ctx.problems.filter((item) => item.level === 'error');
      if (errors.length) {
        reject({ kind: 'index', name: object.name, reason: errors.map((item) => item.message).join(' ; '), sql: object.sql });
        continue;
      }
      ctx.helpers.forEach((helper) => helpers.add(helper));
      ctx.problems.forEach((item) => warn(`index ${object.name}`, item.message));
      const name = pgName(object.name, relationNames);
      if (name !== object.name) warn(`index ${object.name}`, `renommé ${name} (collision ou longueur)`);
      indexes.push({
        name,
        table: table.name,
        unique: parsed.unique,
        partial: !!parsed.where,
        sql: `CREATE ${parsed.unique ? 'UNIQUE ' : ''}INDEX ${quoteIdent(name)} ON ${s}.${quoteIdent(table.name)} (${parts.join(', ')})${where ? ` WHERE ${where}` : ''}`,
      });
    } catch (error) {
      reject({ kind: 'index', name: object.name, reason: `DDL illisible (${(error as Error).message})`, sql: object.sql });
    }
  }

  // ---- Views --------------------------------------------------------------------------------------------------------
  const allColumns = new Map<string, string>();
  tables.forEach((table) => table.columns.forEach((column) => allColumns.set(column.name.toLowerCase(), column.name)));
  const relations = new Map(tables.map((table) => [table.name.toLowerCase(), table.name]));
  const viewObjects = objects.filter((item) => item.type === 'view');
  viewObjects.forEach((view) => relations.set(view.name.toLowerCase(), view.name));
  const views: ViewPlan[] = [];
  for (const object of viewObjects) {
    try {
      const parsed = parseCreateView(object.sql);
      const missing = referencedRelations(parsed.select).filter((name) => !relations.has(name.toLowerCase()));
      if (missing.length) throw new Error(`relations absentes de l’export : ${missing.join(', ')}`);
      const columnNames = (db.prepare('SELECT name FROM pragma_table_xinfo(?)').all(object.name) as { name: string }[]).map((row) => row.name);
      const viewColumns = new Map(allColumns);
      columnNames.forEach((name) => viewColumns.set(name.toLowerCase(), viewColumns.get(name.toLowerCase()) ?? name));
      const ctx: TranslateContext = { schema, mode: 'view', columns: viewColumns, tables: relations, helpers: new Set(), problems: [] };
      const select = translateExpression(parsed.select, ctx);
      const errors = ctx.problems.filter((item) => item.level === 'error');
      if (errors.length) throw new Error(errors.map((item) => item.message).join(' ; '));
      ctx.helpers.forEach((helper) => helpers.add(helper));
      ctx.problems.forEach((item) => warn(`vue ${object.name}`, item.message));
      if (new Set(columnNames.map((name) => name.toLowerCase())).size !== columnNames.length) throw new Error('noms de colonnes en double');
      views.push({
        name: object.name,
        sql: `CREATE VIEW ${s}.${quoteIdent(object.name)} (${columnNames.map(quoteIdent).join(', ')}) AS ${select}`,
        dependsOn: referencedRelations(parsed.select).filter((name) => viewObjects.some((view) => view.name.toLowerCase() === name.toLowerCase())),
      });
      relationNames.add(object.name.toLowerCase());
    } catch (error) {
      relations.delete(object.name.toLowerCase());
      reject({ kind: 'view', name: object.name, reason: (error as Error).message, sql: object.sql });
    }
  }

  // ---- Triggers -----------------------------------------------------------------------------------------------------
  const triggers: TriggerPlan[] = [];
  const triggerColumns = new Map(allColumns);
  for (const object of objects.filter((item) => item.type === 'trigger')) {
    try {
      const parsed = parseCreateTrigger(object.sql);
      const table = tableByName.get(parsed.table.toLowerCase());
      const view = views.find((item) => item.name.toLowerCase() === parsed.table.toLowerCase());
      if (!table && !view) throw new Error(`table ou vue ${parsed.table} non exportée`);
      if (parsed.timing === 'INSTEAD OF' && !view) throw new Error('INSTEAD OF sur une table');
      const columns = table
        ? table.columns.filter((column) => !column.rowid).map((column) => column.name)
        : (db.prepare('SELECT name FROM pragma_table_xinfo(?)').all(view!.name) as { name: string }[]).map((row) => row.name);
      const rowidColumn = table?.columns.find((column) => column.rowid)?.name;
      const rowidAlias = table && !table.withoutRowid ? (table.identityColumns[0] ?? rowidColumn) : undefined;
      const converted = convertTrigger(parsed, {
        name: table?.name ?? view!.name,
        isView: !table,
        columns,
        primaryKey: table?.primaryKey ?? [],
        rowidTable: !!table && !table.withoutRowid && !!rowidAlias,
        rowidAlias,
      }, { schema, columns: triggerColumns, tables: relations, helpers }, functionNames);
      converted.notes.forEach((note) => warn(`déclencheur ${object.name}`, note));
      if (converted.pattern === 'generic') warn(`déclencheur ${object.name}`, 'traduction générique instruction par instruction : comportement à vérifier');
      triggers.push({
        name: object.name,
        table: converted.triggers[0].table,
        pattern: converted.pattern,
        functionName: converted.functionName,
        functionSql: converted.functionSql,
        triggerNames: converted.triggers.map((item) => item.name),
        sql: converted.triggers.map((item) => item.sql),
      });
    } catch (error) {
      reject({ kind: 'trigger', name: object.name, reason: (error as Error).message, sql: object.sql });
    }
  }

  const orderedTables = topologicalOrder(tables);
  const result: ConversionResult = {
    schema,
    sqliteVersion,
    helpers: helperDefinitions(schema, helpers),
    tables: orderedTables,
    indexes,
    foreignKeys,
    triggers,
    views: topologicalOrder(views),
    warnings,
    unsupported,
    ddl: '',
  };
  result.ddl = renderDdl(result);
  return result;
}

function findUniqueIndex(db: DatabaseSync, table: string, columns: string[]): boolean {
  const list = db.prepare('SELECT name, "unique" AS "unique", partial FROM pragma_index_list(?)').all(table) as unknown as IndexListRow[];
  return list.some((index) => {
    if (!index.unique || index.partial) return false;
    const keys = db.prepare('SELECT cid, name FROM pragma_index_xinfo(?) WHERE "key" = 1').all(index.name) as unknown as IndexXInfoRow[];
    return keys.every((key) => key.cid >= 0 && key.name) && sameColumnSet(keys.map((key) => key.name!), columns);
  });
}

export function renderColumn(column: ColumnPlan): string {
  let sql = `${quoteIdent(column.name)} ${column.pgType}`;
  if (column.pgType === 'text') sql += ' COLLATE "C"';
  if (column.generated) sql += ` GENERATED ALWAYS AS (${column.generatedSql}) STORED`;
  else if (column.identity) sql += ' GENERATED BY DEFAULT AS IDENTITY';
  if (column.notNull && !column.identity) sql += ' NOT NULL';
  if (column.defaultSql !== undefined && !column.generated && !column.identity) sql += ` DEFAULT ${column.defaultSql}`;
  return sql;
}

export function renderCreateTable(table: TablePlan, schema: string, options: { inlineChecks?: boolean } = {}): string {
  const lines = [
    ...table.columns.map(renderColumn),
    ...table.constraints,
    ...(options.inlineChecks ?? true ? table.checks.map((check) => `CONSTRAINT ${quoteIdent(check.name)} CHECK (${check.sql})`) : []),
  ];
  return `CREATE TABLE ${quoteIdent(schema)}.${quoteIdent(table.name)} (\n  ${lines.join(',\n  ')}\n)`;
}

export function renderCheck(table: TablePlan, check: CheckPlan, schema: string): string {
  return `ALTER TABLE ${quoteIdent(schema)}.${quoteIdent(table.name)} ADD CONSTRAINT ${quoteIdent(check.name)} CHECK (${check.sql})`;
}

export function renderForeignKey(fk: ForeignKeyPlan, schema: string, options: { notValid?: boolean } = {}): string {
  const s = quoteIdent(schema);
  const actions = `${fk.onUpdate !== 'NO ACTION' ? ` ON UPDATE ${fk.onUpdate}` : ''}${fk.onDelete !== 'NO ACTION' ? ` ON DELETE ${fk.onDelete}` : ''}`;
  // SQLite checks immediate constraints at the end of each statement: DEFERRABLE INITIALLY IMMEDIATE matches that.
  return `ALTER TABLE ${s}.${quoteIdent(fk.table)} ADD CONSTRAINT ${quoteIdent(fk.name)} FOREIGN KEY (${fk.columns.map(quoteIdent).join(', ')}) `
    + `REFERENCES ${s}.${quoteIdent(fk.refTable)} (${fk.refColumns.map(quoteIdent).join(', ')})${actions} `
    + `DEFERRABLE INITIALLY ${fk.initiallyDeferred ? 'DEFERRED' : 'IMMEDIATE'}${options.notValid ? ' NOT VALID' : ''}`;
}

function commentBlock(text: string): string {
  return text.split('\n').map((line) => `-- ${line}`.trimEnd()).join('\n');
}

export function renderDdl(result: ConversionResult): string {
  const s = quoteIdent(result.schema);
  const out: string[] = [
    `-- Schéma PostgreSQL généré depuis SQLite ${result.sqliteVersion} par scripts/export-postgres.ts (Alpha).`,
    `-- ${result.tables.length} tables, ${result.indexes.length} index, ${result.foreignKeys.length} clés étrangères, ${result.triggers.length} déclencheurs, ${result.views.length} vues.`,
    `-- Avertissements : ${result.warnings.length} (liste en fin de fichier). PostgreSQL 13+ requis (gen_random_uuid, identity).`,
    '',
    'SET standard_conforming_strings = on;',
    'SET client_min_messages = warning;',
    'BEGIN;',
    `CREATE SCHEMA IF NOT EXISTS ${s};`,
    `SET LOCAL search_path TO ${s}, public;`,
  ];
  const section = (title: string, statements: string[]) => {
    if (!statements.length) return;
    out.push('', `-- ${title}`, ...statements.map((sql) => `${sql};`));
  };
  section('Fonctions d’équivalence SQLite', result.helpers.map((helper) => helper.sql));
  section('Tables (ordre des dépendances)', result.tables.map((table) => renderCreateTable(table, result.schema)));
  section('Index', result.indexes.map((index) => index.sql));
  section('Clés étrangères', result.foreignKeys.map((fk) => renderForeignKey(fk, result.schema)));
  section('Déclencheurs', result.triggers.flatMap((trigger) => [trigger.functionSql, ...trigger.sql]));
  section('Vues', result.views.map((view) => view.sql));
  out.push('', 'COMMIT;');
  if (result.warnings.length) out.push('', '-- Avertissements :', ...result.warnings.map((warning) => commentBlock(`* ${warning}`)));
  for (const item of result.unsupported.filter((entry) => entry.sql)) {
    out.push('', `-- Non converti (${item.kind} ${item.name}) : ${item.reason}`, commentBlock(item.sql!));
  }
  return `${out.join('\n')}\n`;
}
